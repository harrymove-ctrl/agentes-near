/**
 * Generates `src/icons/source.ts` from the design files in
 * `docs/design/icons/*.svg` (20px grid, 1.6 stroke). Run `bun run icons` in
 * `packages/ui` after changing an icon there. The logo marks are filled
 * shapes and live in the Logo component instead.
 */
import { Glob } from "bun";

const DIR = new URL("../../../docs/design/icons/", import.meta.url).pathname;
const OUT = new URL("../src/icons/source.ts", import.meta.url).pathname;

/** Design files are named in Portuguese; code uses English names. */
const NAMES: Record<string, string> = {
  agente: "agent",
  aguardando: "waiting",
  anexo: "attach",
  aprovar: "approve",
  busca: "search",
  canal: "channel",
  enviar: "send",
  mensagem: "message",
  pessoa: "person",
};

type Shape = [tag: "path" | "circle" | "rect" | "line" | "polyline", attrs: Record<string, string>];

export function parseSvg(svg: string): Shape[] {
  const shapes: Shape[] = [];
  for (const match of svg.matchAll(/<(path|circle|rect|line|polyline)\b([^>]*?)\/?>/g)) {
    const attrs: Record<string, string> = {};
    for (const a of (match[2] ?? "").matchAll(/([a-zA-Z-]+)="([^"]*)"/g)) {
      if (a[1] && a[2] !== undefined) attrs[a[1]] = a[2];
    }
    shapes.push([match[1] as Shape[0], attrs]);
  }
  return shapes;
}

if (import.meta.main) {
  const entries: string[] = [];
  const files = [...new Glob("*.svg").scanSync(DIR)].sort();
  for (const file of files) {
    const base = file.replace(/\.svg$/, "");
    if (base.startsWith("logo-")) continue;
    const name = NAMES[base];
    if (!name) throw new Error(`docs/design/icons/${file}: add it to NAMES in scripts/generate-icons.ts`);
    const shapes = parseSvg(await Bun.file(DIR + file).text());
    entries.push(`  /** docs/design/icons/${file} */\n  ${name}: ${JSON.stringify(shapes)},`);
  }
  const out = `// Generated by scripts/generate-icons.ts from docs/design/icons. Do not edit by hand.
import type { IconShape } from "./types";

export const sourceIcons = {
${entries.join("\n")}
} satisfies Record<string, IconShape[]>;
`;
  await Bun.write(OUT, out);
  console.log(`wrote ${entries.length} icons to src/icons/source.ts`);
}
