/**
 * Labeled conversations for `eval:media` (ADR 0091 §4): an agent's reply and what came before it, whether a
 * sticker or a GIF right after it would be natural and welcome among teammates (`send`), and, when it would,
 * the moods and GIF categories that fit. Every reply passes the step's free checks (short, no code, no table,
 * no question at the end): production asks Jev only about such replies. Names are neutral (Acme, Dev, Infra).
 */
import type { AgentMediaInput } from "../../src/agent-media";
import type { AGENT_GIF_CATEGORIES, AGENT_STICKER_MOODS } from "../../src/media";

type Mood = (typeof AGENT_STICKER_MOODS)[number];
type GifCategory = (typeof AGENT_GIF_CATEGORIES)[number];

export interface MediaCase {
  id: string;
  lang: "pt-BR" | "en";
  where: AgentMediaInput["where"];
  agent: AgentMediaInput["agent"];
  /** Before the reply, oldest first. */
  conversation: AgentMediaInput["conversation"];
  reply: string;
  /** A sticker or a GIF right after this reply would be natural and welcome. */
  send: boolean;
  /** When `send`: the moods that fit (any of them is right). */
  moods?: Mood[];
  /** When `send`: the GIF categories that fit (scored with `--gif`). */
  gifs?: GifCategory[];
}

